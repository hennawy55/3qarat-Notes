const fs = require('fs');
const assert = require('assert');
const read = name => fs.readFileSync(name, 'utf8');

const app = read('app.js');
const edge = read('supabase/functions/smartnote-auth/index.ts');
const migrationAuth = read('supabase/migrations/202611240003_custom_auth.sql');
const migrationDb = read('supabase/migrations/202611240006_atomic_user_database.sql');
const html = read('index.html');
const worker = read('sw.js');
const packageJson = JSON.parse(read('package.json'));
const manifest = JSON.parse(read('manifest.json'));
const supabaseConfig = read('supabase/config.toml');

assert(app.includes("SUPABASE_URL='https://cantyrqkkbqwrajghluw.supabase.co'") && app.includes("'/functions/v1/smartnote-auth'"), 'Client must target Supabase Edge Function');
assert(app.includes("'apikey'") && app.includes("'x-smartnote-session'"), 'Client must send publishable key and custom session headers');
assert(!app.includes('script.google.com/macros'), 'Google Apps Script must no longer be the active API');
assert(app.includes("action:'assignment_history'") && app.includes("action:'assignment_targets'") && app.includes("action:'reassignment_targets'"), 'Assigned follow-up UI actions must remain wired');
assert(edge.includes('function assignmentAction') && edge.includes('function notificationAction'), 'Edge Function must implement assigned follow-ups and notification operations');
assert(edge.includes('bodyToken') && edge.includes('b.oldPassword'), 'Session and password request compatibility must be supported');
assert(edge.includes('p_expected_revision') && edge.includes('revision:Number(meta?.revision||0)'), 'Edge Function must read and return database revisions');
assert(migrationAuth.includes('drop constraint if exists profiles_id_fkey'), 'Custom login identities must not require Supabase Auth users');
assert(migrationDb.includes('user_database_meta') && migrationDb.includes("raise exception 'data_conflict'"), 'Database replacement must guard against cross-device stale writes');
assert(html.includes('./lucide.min.js') && !html.includes('lucide@latest'), 'Lucide must be loaded from a local pinned asset');
assert(worker.includes('smartnote-offline-shell-v27') && worker.includes('./lucide.min.js'), 'Service worker must cache refreshed Lucide asset');
assert(packageJson.dependencies.lucide === '0.468.0', 'Lucide version must remain pinned');
assert(packageJson.scripts['prepare:android'].includes('node_modules/lucide/dist/umd/lucide.min.js'), 'Android build must bundle the local Lucide runtime');
assert(packageJson.scripts['prepare:web'].includes('node_modules/lucide/dist/umd/lucide.min.js'), 'Web build must bundle the local Lucide runtime');
assert(manifest.icons.some(icon => icon.src === 'icons/smartnote-icon.svg'), 'PWA manifest must reference the app icon');
assert(supabaseConfig.includes('verify_jwt = false'), 'Custom-session Edge Function must disable gateway JWT verification');
console.log('SmartNote Supabase migration smoke checks passed.');
